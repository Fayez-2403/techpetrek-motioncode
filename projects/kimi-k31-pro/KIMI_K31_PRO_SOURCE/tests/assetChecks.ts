// Asset checks: every file the film can load (public/) is recorded in ASSET_SOURCES.md, fonts ship with their OFL
// licences, B/C scenes render their provenance label, and nothing from the reference video is in the project.
import { existsSync, readFileSync, readdirSync, statSync } from 'node:fs';
import path from 'node:path';
import type { Check } from './run';

const ROOT = path.resolve(__dirname, '..');
const walk = (d: string): string[] => readdirSync(d).flatMap((f) => { const p = path.join(d, f); return statSync(p).isDirectory() ? walk(p) : [p]; });

export function assetChecks(): Check[] {
  const checks: Check[] = [];
  const add = (name: string, ok: boolean, detail = '') => checks.push({ name, ok, detail });
  const sources = existsSync(path.join(ROOT, 'ASSET_SOURCES.md')) ? readFileSync(path.join(ROOT, 'ASSET_SOURCES.md'), 'utf8') : '';
  add('ASSET_SOURCES.md exists', sources.length > 0);
  for (const f of walk(path.join(ROOT, 'public'))) {
    const rel = path.relative(path.join(ROOT, 'public'), f).replace(/\\/g, '/');
    if (rel.startsWith('audio/')) continue;            // generated by audio-src (documented as a group)
    add(`recorded in ASSET_SOURCES.md: public/${rel}`, sources.includes(rel));
  }
  add('generated audio documented', /audio\/vo_\*|audio\/mix_\*/.test(sources));
  for (const [font, lic] of [['Unbounded-VF.ttf', 'OFL-Unbounded.txt'], ['InstrumentSans-VF.ttf', 'OFL-InstrumentSans.txt'], ['JetBrainsMono-VF.ttf', 'OFL-JetBrainsMono.txt']]) {
    const ok = existsSync(path.join(ROOT, 'public/fonts', lic)) && /SIL Open Font License/.test(readFileSync(path.join(ROOT, 'public/fonts', lic), 'utf8'));
    add(`font licence present: ${font}`, existsSync(path.join(ROOT, 'public/fonts', font)) && ok);
  }
  // provenance labels
  const manifest = readFileSync(path.join(ROOT, 'src/data/sceneManifest.ts'), 'utf8');
  for (const m of manifest.matchAll(/provenance: '([A-Za-z]+)', component: (\w+)/g)) {
    const [, prov, comp] = m;
    if (prov !== 'B' && prov !== 'C') continue;
    const src = readFileSync(path.join(ROOT, 'src/scenes', `${comp}.tsx`), 'utf8');
    if (comp === 'FinalMontage') { add('montage only reuses labelled scenes', !/ProvenanceLabel kind=/.test(src) && /CodingWorld/.test(src)); continue; }
    add(`${comp} renders its ${prov} label`, new RegExp(`<ProvenanceLabel[^>]*kind="${prov}"`).test(src));
  }
  const refHits = walk(ROOT).filter((f) => !f.includes('node_modules') && !f.includes(`${path.sep}.git${path.sep}`) && /refvid|DIyHTpfWctU/i.test(f));
  add('no reference-video files in the project', refHits.length === 0, refHits.slice(0, 3).join(', '));
  return checks;
}
